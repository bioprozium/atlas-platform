def violates(connection, statement, state, constraint=None):
    with pytest.raises(IntegrityError) as error, connection.begin_nested():
        connection.execute(statement)
    assert error.value.orig.sqlstate == state
    if constraint is not None:
        assert error.value.orig.diag.constraint_name == constraint


def test_registry_foreign_keys_uniqueness_and_checks(owner, registry):
    _, structures, asset_ids, versions, file_metadata = registry
    violates(owner, assets.insert().values(code="femur-detail", title="Duplicate"), "23505")
    violates(owner, assets.insert().values(code="Invalid", title="New asset"), "23514")
    violates(owner, assets.insert().values(code="other-asset", title="  "), "23514")
    insertion = asset_versions.insert().values(
        asset_id=asset_ids["femur-detail"], version="v3", **file_metadata
    )
    violates(owner, insertion.values(version="v1.0"), "23505")
    violates(owner, insertion.values(asset_id=UNKNOWN_ID), "23503")
    violates(owner, insertion.values(sha256="z" * 64), "23514", "ck_asset_versions_sha256")
    violates(owner, insertion.values(storage_reference="../model.glb"), "23514")
    violates(owner, insertion.values(file_size=25), "23514", "ck_asset_versions_size")
    violates(owner, insertion.values(validation_state="bad"), "23514")

    link = anatomy_asset_links.insert().values(
        structure_id=structures["left-femur"],
        version_id=versions["femur-detail", "v1.1"],
    )
    violates(owner, link.values(role="another-role"), "23505", "uq_anatomy_asset_links_pair")
    violates(owner, link.values(structure_id=UNKNOWN_ID), "23503")
    violates(owner, link.values(version_id=UNKNOWN_ID), "23503")
    violates(owner, asset_sources.insert().values(version_id=UNKNOWN_ID, **ORIGINAL), "23503")
    violates(
        owner,
        asset_sources.insert().values(
            version_id=versions["femur-detail", "v2"], **(ORIGINAL | {"license_reference": " "})
        ),
        "23514",
        "ck_asset_sources_required_text",
    )


def test_asset_and_version_identity_are_immutable(owner, registry):
    _, _, asset_ids, version_ids, _ = registry
    asset_id = asset_ids["femur-detail"]
    asset_update = update(assets).where(assets.c.id == asset_id)
    for changes in ({"code": "replacement"}, {"id": UNKNOWN_ID}):
        violates(owner, asset_update.values(**changes), "23514")
    violates(owner, delete(assets).where(assets.c.id == asset_id), "23514")

    version_id = version_ids["femur-detail", "v1.1"]
    version_update = update(asset_versions).where(asset_versions.c.id == version_id)
    for changes in (
        {"version": "v2.1"},
        {"id": UNKNOWN_ID},
        {"asset_id": asset_ids["femur-overview"]},
        {"sha256": "1" * 64, "storage_reference": glb_storage_reference("1" * 64)},
        {"file_size": 28},
    ):
        violates(owner, version_update.values(**changes), "23514")
    owner.execute(version_update.values(publication_state="withdrawn"))
    violates(owner, version_update.values(file_size=28), "23514")
    violates(owner, delete(asset_versions).where(asset_versions.c.id == version_id), "23514")


def test_publication_requires_current_validation_and_rights(owner, registry):
    _, _, _, versions, _ = registry
    draft_id = versions["femur-detail", "v2"]
    version_update = update(asset_versions).where(asset_versions.c.id == draft_id)
    publish = version_update.values(publication_state="published")
    violates(owner, publish, "23514", "ck_asset_versions_publishable")
    source_id = owner.scalar(
        asset_sources.insert()
        .values(version_id=draft_id, **ORIGINAL)
        .returning(asset_sources.c.id)
    )
    wrong_source_id = owner.scalar(
        select(asset_sources.c.id).where(
            asset_sources.c.version_id == versions["femur-detail", "v1.1"]
        )
    )
    violates(
        owner,
        publish.values(validation_state="valid", primary_source_id=wrong_source_id, **REVIEW),
        "23503",
        "fk_asset_versions_primary_source",
    )
    violates(
        owner,
        publish.values(primary_source_id=source_id, **REVIEW),
        "23514",
        "ck_asset_versions_publishable",
    )
    violates(
        owner,
        publish.values(validation_state="valid", primary_source_id=source_id),
        "23514",
        "ck_asset_versions_publishable",
    )

    owner.execute(
        publish.values(validation_state="valid", primary_source_id=source_id, **REVIEW)
    )
    correction = (
        update(asset_sources)
        .where(asset_sources.c.id == source_id)
        .values(attribution="Updated fixture attribution")
    )
    violates(owner, correction, "23514", "ck_asset_versions_publishable")
    violates(
        owner,
        asset_sources.insert().values(version_id=draft_id, **ORIGINAL),
        "23514",
        "ck_asset_versions_publishable",
    )
    violates(
        owner,
        delete(asset_sources).where(asset_sources.c.id == source_id),
        "23514",
        "ck_asset_versions_publishable",
    )

    owner.execute(version_update.values(publication_state="withdrawn"))
    owner.execute(correction)
    assert owner.execute(
        select(
            asset_versions.c.rights_verified_at, asset_versions.c.rights_review_reference
        ).where(asset_versions.c.id == draft_id)
    ).one() == (None, None)
    violates(owner, publish, "23514", "ck_asset_versions_publishable")
    owner.execute(publish.values(**REVIEW))


def test_runtime_cannot_write_registry(registry, postgres_url):
    runtime = create_engine(postgres_url(RUNTIME_ROLE), poolclass=NullPool)
    try:
        with runtime.connect() as connection:
            for table in (assets, asset_versions, asset_sources, anatomy_asset_links):
                assert connection.execute(select(table).limit(1)).first() is not None
                with pytest.raises(ProgrammingError) as error, connection.begin_nested():
                    connection.execute(delete(table))
                assert error.value.orig.sqlstate == "42501"
    finally:
        runtime.dispose()


def get(client, path, params=None):
    response = client.get(f"/api/v1{path}", params=params)
    assert response.status_code == 200, response.text
    return response.json()


def test_asset_visibility_pagination_and_version_specific_attribution(client, registry):
    _, _, _, _, file_metadata = registry
    page = get(client, "/assets", {"q": "FEMUR", "limit": 1})
    assert (page["limit"], page["offset"], page["has_more"]) == (1, 0, True)
    latest = {key: file_metadata[key] for key in ("sha256", "file_size", "format", "mime_type")}
    assert page["items"] == [
        {
            "code": "femur-detail",
            "title": "Femur Detail",
            "latest_version": dict(latest, version="v1.1", sources=[THIRD_PARTY_RECORD]),
        }
    ]
    next_page = get(client, "/assets", {"limit": 1, "offset": 1})
    assert [item["code"] for item in next_page["items"]] == ["femur-overview"]
    assert next_page["has_more"] is False
    assert get(client, "/assets", {"q": "%"})["items"] == []

    detail = get(client, "/assets/femur-detail", {"limit": 1, "offset": 1})
    assert detail == {
        "code": "femur-detail",
        "title": "Femur Detail",
        "versions": {
            "items": [dict(latest, version="v1.0", sources=[ORIGINAL])],
            "limit": 1,
            "offset": 1,
            "has_more": False,
        },
    }
    assert get(client, "/assets/femur-detail", {"offset": 10})["versions"]["items"] == []
    assert get(client, "/assets/femur-detail/versions/v1.0") == dict(
        latest, code="femur-detail", title="Femur Detail", version="v1.0", sources=[ORIGINAL]
    )


def test_structure_links_are_many_to_many_and_paginated(client):
    page = get(client, "/anatomy/structures/femur/assets", {"limit": 2})
    assert page["has_more"] is True
    assert [(item["code"], item["version"], item["role"]) for item in page["items"]] == [
        ("femur-detail", "v1.1", "primary"),
        ("femur-detail", "v1.0", "context"),
    ]
    next_page = get(client, "/anatomy/structures/femur/assets", {"limit": 2, "offset": 2})
    assert [item["code"] for item in next_page["items"]] == ["femur-overview"]
    assert next_page["has_more"] is False
    assert (
        get(client, "/anatomy/structures/femur/assets", {"q": "Overview"})["items"]
        == next_page["items"]
    )

    other_structure = get(client, "/anatomy/structures/left-femur/assets")
    assert other_structure["items"] == [dict(page["items"][0], role=None)]
    assert get(client, "/anatomy/structures/heart/assets")["items"] == []


